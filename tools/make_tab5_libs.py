#!/usr/bin/env python3
"""Build the PlatformIO libraries package used by the Tab5 build.

The stock pioarduino libraries for the ESP32-P4 run PSRAM at 80 MHz, which is too
slow for the Tab5's 1280x720 screen (the display controller runs out of data and
the picture flashes), and their ESP-Hosted Wi-Fi driver is much older than the
firmware on the Tab5's ESP32-C6. Espressif's official Arduino-ESP32 release also
ships "esp32p4_es" libraries (for P4 chip revisions before 3.0, like the Tab5's)
built with 200 MHz PSRAM and a current ESP-Hosted. They come in the Arduino IDE
layout, so this script repackages them for PlatformIO:

  - unzips esp32p4_es-libs-<ver>.zip into <out>/esp32p4/
  - writes package.json
  - generates esp32p4/pioarduino-build.py from the package's flags/ files

Usage:  python3 tools/make_tab5_libs.py [version] [output dir]
        (defaults: 3.3.10, ~/.platformio/custom/framework-arduinoespressif32-libs-tab5)
"""
import json
import os
import shlex
import shutil
import sys
import urllib.request
import zipfile

VER = sys.argv[1] if len(sys.argv) > 1 else "3.3.10"
OUT = os.path.expanduser(sys.argv[2] if len(sys.argv) > 2 else
                         "~/.platformio/custom/framework-arduinoespressif32-libs-tab5")
URL = f"https://github.com/espressif/arduino-esp32/releases/download/{VER}/esp32p4_es-libs-{VER}.zip"


def tokens(path):
    with open(path) as f:
        return shlex.split(f.read())


def main():
    os.makedirs(OUT, exist_ok=True)
    zpath = os.path.join(OUT, f"esp32p4_es-libs-{VER}.zip")
    if not os.path.exists(zpath):
        print("downloading", URL)
        urllib.request.urlretrieve(URL, zpath)
    dst = os.path.join(OUT, "esp32p4")
    if os.path.exists(dst):
        shutil.rmtree(dst)
    with zipfile.ZipFile(zpath) as z:
        z.extractall(OUT)
    os.rename(os.path.join(OUT, "esp32p4_es-libs"), dst)

    flags = os.path.join(dst, "flags")
    c_flags = tokens(os.path.join(flags, "c_flags"))
    cpp_flags = tokens(os.path.join(flags, "cpp_flags"))
    s_flags = tokens(os.path.join(flags, "S_flags"))
    ld_flags = tokens(os.path.join(flags, "ld_flags"))
    ld_scripts = tokens(os.path.join(flags, "ld_scripts"))
    ld_libs = tokens(os.path.join(flags, "ld_libs"))
    inc = tokens(os.path.join(flags, "includes"))
    includes = [inc[i + 1] for i in range(len(inc) - 1) if inc[i] == "-iwithprefixbefore"]
    defines = []
    for d in tokens(os.path.join(flags, "defines")):
        if not d.startswith("-D"):
            continue
        name, _, val = d[2:].partition("=")
        if not val:
            defines.append(repr(name))
        elif val.startswith('"'):
            defines.append("(%r, '\\\\\"%s\\\\\"')" % (name, val.strip('"')))
        else:
            defines.append("(%r, %r)" % (name, val))

    # compiler flags shared by C and C++ go to CCFLAGS, the rest to CFLAGS / CXXFLAGS
    common = [f for f in c_flags if f in cpp_flags]
    cflags = [f for f in c_flags if f not in common]
    cxxflags = [f for f in cpp_flags if f not in common]

    mem = 'board_config.get("build.arduino.memory_type", (board_config.get("build.flash_mode", "dio") + "_qspi"))'
    lines = [
        "# Generated by tools/make_tab5_libs.py from Arduino-ESP32 %s esp32p4_es-libs flags/." % VER,
        "from os.path import basename, join",
        "from SCons.Script import DefaultEnvironment",
        "env = DefaultEnvironment()",
        'FRAMEWORK_DIR = env.PioPlatform().get_package_dir("framework-arduinoespressif32")',
        'FRAMEWORK_SDK_DIR = env.PioPlatform().get_package_dir("framework-arduinoespressif32-libs")',
        "board_config = env.BoardConfig()",
        "SDK = join(FRAMEWORK_SDK_DIR, 'esp32p4')",
        "env.Append(",
        "    ASFLAGS=%r," % s_flags,
        '    ASPPFLAGS=["-x", "assembler-with-cpp"],',
        "    CFLAGS=%r," % cflags,
        "    CXXFLAGS=%r," % cxxflags,
        "    CCFLAGS=%r," % (["-Os"] + common + ["-MMD"]),
        "    LINKFLAGS=%r + %r + ['-Wl,-Map=\"%%s\"' %% join('${BUILD_DIR}', '${PROGNAME}.map')]," % (ld_flags, ld_scripts),
        "    CPPPATH=[%s] + [join(SDK, %s, 'include'), join(FRAMEWORK_DIR, 'cores', board_config.get('build.core'))]," % (
            ", ".join("join(SDK, 'include', %r)" % i for i in includes), mem),
        "    LIBPATH=[join(SDK, 'lib'), join(SDK, 'ld'), join(SDK, %s)]," % mem,
        "    LIBS=%r," % ld_libs,
        "    CPPDEFINES=[%s] + [" % ", ".join(defines),
        '        "ARDUINO_ARCH_ESP32", "CHIP_HAVE_CONFIG_H", ("ESP32", "ESP32"), ("F_CPU", "$BOARD_F_CPU"),',
        '        ("ARDUINO", 10812),',
        '        ("ARDUINO_VARIANT", \'\\\\"%s\\\\"\' % board_config.get("build.variant").replace(\'"\', "")),',
        '        ("ARDUINO_BOARD", \'\\\\"%s\\\\"\' % board_config.get("name").replace(\'"\', "")),',
        '        "ARDUINO_PARTITION_%s" % basename(board_config.get("build.partitions", "default.csv")).replace(".csv", "").replace("-", "_"),',
        "    ],",
        ")",
    ]
    with open(os.path.join(dst, "pioarduino-build.py"), "w") as f:
        f.write("\n".join(lines) + "\n")

    with open(os.path.join(OUT, "package.json"), "w") as f:
        json.dump({
            "name": "framework-arduinoespressif32-libs",
            "description": "Arduino-ESP32 %s esp32p4_es libraries (200 MHz PSRAM) for the M5Stack Tab5" % VER,
            "version": "5.5.4+tab5es.%s" % VER,
        }, f, indent=2)
    os.remove(zpath)
    print("ready:", OUT)


if __name__ == "__main__":
    main()
